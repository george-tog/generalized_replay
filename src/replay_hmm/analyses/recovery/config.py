# question, not a coverage one: does data generated by this kernel get recovered as this
# kernel, or absorbed by its sibling? That has to be asked ACROSS the cube, since a pair can
# be cleanly separable at the fitted point and degenerate over most of the rest of it, and one
# point cannot tell those two cases apart.
