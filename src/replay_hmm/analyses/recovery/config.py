# (`momentum_refit_grid`) so a coarse-grid run cannot be mistaken for a full-grid one.
#
# It is NOT free of consequence: a coarser grid gives momentum a worse best fit on its own
# data while continuous_EM competes at a continuously optimised sigma, which biases the
# confusion matrix against momentum. A coarse-grid run therefore understates momentum's
# recoverability.
