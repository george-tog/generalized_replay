# point at the ceiling. (Ground truth stays honest either way -- true_params is read back
# off the generator object after clipping -- but the sweep stops being informative.)
#
# The 0.9 margin keeps generators off the cap itself, where the logistic is saturated and
# "recovery" would test the boundary rather than the estimator. The floor keeps them off
# the opposite degeneracy, where the Gaussian collapses toward a delta and merely
# duplicates what kappa already does.
DEFAULT_GRID_SIGMA_MIN = 0.5
