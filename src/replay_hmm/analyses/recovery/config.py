@dataclass(frozen=True)
class RecoveryOutputPaths:
    """Output paths of a grid or random-sample recovery run."""

    filepath_rows_csv: Path
    filepath_summary_json: Path
    filepath_npz: Path
    filepath_heatmap_png: Path


def momentum_refit_grid_label(n_a: int, n_sigma_v: int) -> str:
    """`"4x5"` -- the momentum refit lattice, as one short token.

    Recorded on every row and, when non-default, in the output filenames. Both matter: the
    filename keeps a spot-check's shards from colliding with the main run's, and the column
    makes the mixture visible in the data if two runs' rows are ever loaded together anyway.
    """
    return f"{int(n_a)}x{int(n_sigma_v)}"


def _momentum_refit_grid_from_dict(hmm_dict) -> str | None:
    """The label for whatever momentum model is actually on the refit ballot, or None.

    Derived from the model rather than from the CLI arguments so it cannot disagree with the
    grid the refit really searched.
    """
    model = (hmm_dict or {}).get("momentum")
    if model is None:
        return None
    return momentum_refit_grid_label(len(model.a_values), len(model.sigma_v_values))


def _recovery_output_paths(
    paths,
    generator_mode: str,
    momentum_grid_label: str | None = None,
) -> RecoveryOutputPaths:
    """Use separate filenames for generator modes so skip-process can disambiguate runs.

    `momentum_grid_label` appends a `__momgrid<label>` token when the momentum refit grid is
    not the recovery default, for the same reason `sigma_cap_tag_suffix_cm` appends
    `__sigmacap<v>cm`: nothing else in the path or the collision guard records it, so without the
    token a full-grid spot-check would overwrite a coarse-grid shard of the same index
    -- or, unsharded, be silently ignored by the plotter, which prefers `_shard*` files
    whenever any exist. At the default the token is empty.
    """
    def tagged(name: str) -> str:
        if not momentum_grid_label:
            return name
        stem, dot, ext = name.rpartition(".")
        return f"{stem}__momgrid{momentum_grid_label}{dot}{ext}"

    if generator_mode == "grid":
        return RecoveryOutputPaths(
            filepath_rows_csv=paths.dir_recovery_results / tagged("synthetic_recovery_grid_rows.csv"),
            filepath_summary_json=paths.dir_recovery_results / tagged("synthetic_recovery_grid_summary.json"),
            filepath_npz=paths.dir_recovery_results / tagged("synthetic_recovery_grid_scores.npz"),
            filepath_heatmap_png=paths.dir_recovery_figures / tagged("synthetic_recovery_grid_val_loglik.png"),
        )

    if generator_mode == "random":
        return RecoveryOutputPaths(
            filepath_rows_csv=paths.dir_recovery_results / tagged("synthetic_recovery_random_rows.csv"),
            filepath_summary_json=paths.dir_recovery_results / tagged("synthetic_recovery_random_summary.json"),
            filepath_npz=paths.dir_recovery_results / tagged("synthetic_recovery_random_scores.npz"),
            filepath_heatmap_png=paths.dir_recovery_figures / tagged("synthetic_recovery_random_val_loglik.png"),
        )

    raise ValueError(f"Unknown generator mode: {generator_mode}")


def _with_shard_suffix(
    output_paths: RecoveryOutputPaths,
    generator_shard_index: int,
    generator_num_shards: int,
) -> RecoveryOutputPaths:
    """Use shard-specific filenames when splitting a generator sweep."""
    if int(generator_num_shards) <= 1:
        return output_paths

    suffix = f"_shard{int(generator_shard_index):04d}-of{int(generator_num_shards):04d}"

    def add_suffix(path: Path) -> Path:
        return path.with_name(f"{path.stem}{suffix}{path.suffix}")

    return RecoveryOutputPaths(
        filepath_rows_csv=add_suffix(output_paths.filepath_rows_csv),
        filepath_summary_json=add_suffix(output_paths.filepath_summary_json),
        filepath_npz=add_suffix(output_paths.filepath_npz),
        filepath_heatmap_png=add_suffix(output_paths.filepath_heatmap_png),
    )
