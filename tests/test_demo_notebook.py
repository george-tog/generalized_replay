"""Executes notebooks/kernel_comparison_demo.ipynb end to end and checks what it reports.

Part 3 runs only when data/ and the saved Pfeiffer fit are present, and skips itself otherwise.
Set RUN_NOTEBOOK_TESTS=1 to run it.
"""
import os
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
NOTEBOOK = ROOT / "notebooks" / "kernel_comparison_demo.ipynb"

pytestmark = pytest.mark.skipif(
    os.environ.get("RUN_NOTEBOOK_TESTS") != "1",
    reason="Set RUN_NOTEBOOK_TESTS=1 to execute the demo notebook.",
)


def _stream(nb, name: str) -> str:
    return "".join(
        "".join(o.get("text", ""))
        for cell in nb.cells if cell.cell_type == "code"
        for o in cell.get("outputs", []) if o.get("output_type") == "stream" and o.get("name") == name
    )


def test_demo_notebook_runs_and_recovers_both_generators():
    nbformat = pytest.importorskip("nbformat")
    nbclient = pytest.importorskip("nbclient")

    nb = nbformat.read(NOTEBOOK, as_version=4)
    env_path = os.environ.get("PYTHONPATH", "")
    os.environ["PYTHONPATH"] = os.pathsep.join(p for p in (str(ROOT / "src"), env_path) if p)
    try:
        nbclient.NotebookClient(nb, timeout=900, kernel_name="python3",
                                resources={"metadata": {"path": str(ROOT)}}).execute()
    finally:
        os.environ["PYTHONPATH"] = env_path

    out = _stream(nb, "stdout")
    assert "generated by TCM-SR      -> best held-out kernel: TCM-SR" in out
    assert "generated by Continuous  -> best held-out kernel: Continuous" in out
    assert "Part 1 inputs: ['inputs look consistent']" in out
    assert "[cv-task]" not in out + _stream(nb, "stderr")
    if "Skipping Part 3" not in out:
        assert "best kernel: refit Sym. TCM-SR, saved Sym. TCM-SR" in out
